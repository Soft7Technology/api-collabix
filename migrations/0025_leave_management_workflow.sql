
-- 0025_leave_management_workflow.sql
-- Leave management workflow, reporting assignments,
-- recipient-specific notifications and email outbox.
-- 1. Reporting relationships
ALTER TABLE users
  ADD COLUMN manager_id VARCHAR NULL,
  ADD COLUMN team_lead_id VARCHAR NULL;

ALTER TABLE users
  ADD CONSTRAINT users_manager_id_fkey
    FOREIGN KEY (manager_id)
    REFERENCES users(id)
    ON DELETE SET NULL,
  ADD CONSTRAINT users_team_lead_id_fkey
    FOREIGN KEY (team_lead_id)
    REFERENCES users(id)
    ON DELETE SET NULL,
  ADD CONSTRAINT users_manager_not_self
    CHECK (manager_id IS NULL OR manager_id <> id),
  ADD CONSTRAINT users_team_lead_not_self
    CHECK (team_lead_id IS NULL OR team_lead_id <> id);

CREATE INDEX idx_users_manager_id
  ON users(manager_id);

CREATE INDEX idx_users_team_lead_id
  ON users(team_lead_id);

-- 2. Leave review tracking
ALTER TABLE leaves
  ADD COLUMN reviewed_by VARCHAR NULL,
  ADD COLUMN reviewed_at TIMESTAMPTZ NULL,
  ADD COLUMN rejection_reason TEXT NULL;

ALTER TABLE leaves
  ADD CONSTRAINT leaves_reviewed_by_fkey
    FOREIGN KEY (reviewed_by)
    REFERENCES users(id)
    ON DELETE SET NULL;

ALTER TABLE leaves
  ADD CONSTRAINT leaves_valid_status
    CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'));

CREATE INDEX idx_leaves_org_status
  ON leaves(organization_id, status);

CREATE INDEX idx_leaves_member_dates
  ON leaves(member_id, start_date, end_date);

-- 3. Recipient-specific notifications
CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id UUID NOT NULL
    REFERENCES organizations(id) ON DELETE CASCADE,
  recipient_id VARCHAR NOT NULL
    REFERENCES users(id) ON DELETE CASCADE,
  actor_id VARCHAR NULL
    REFERENCES users(id) ON DELETE SET NULL,
  type VARCHAR(100) NOT NULL,
  title VARCHAR(255) NOT NULL,
  message TEXT NOT NULL,
  entity_type VARCHAR(100),
  entity_id VARCHAR,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  dedupe_key VARCHAR(255) UNIQUE,
  read_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_notifications_recipient_unread
  ON notifications(recipient_id, created_at DESC)
  WHERE read_at IS NULL;

CREATE INDEX idx_notifications_org_created
  ON notifications(organization_id, created_at DESC);

CREATE INDEX idx_notifications_entity
  ON notifications(entity_type, entity_id);

-- 4. Durable email outbox
CREATE TABLE email_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id UUID NOT NULL
    REFERENCES organizations(id) ON DELETE CASCADE,
  recipient_email VARCHAR(320) NOT NULL,
  template VARCHAR(100) NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  dedupe_key VARCHAR(255) UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  attempt_count INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL DEFAULT 5,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  locked_at TIMESTAMPTZ NULL,
  sent_at TIMESTAMPTZ NULL,
  last_error TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT email_outbox_valid_status
    CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'FAILED')),

  CONSTRAINT email_outbox_valid_attempts
    CHECK (
      attempt_count >= 0
      AND max_attempts > 0
      AND attempt_count <= max_attempts
    )
);

CREATE INDEX idx_email_outbox_pending
  ON email_outbox(status, next_attempt_at)
  WHERE status IN ('PENDING', 'PROCESSING');